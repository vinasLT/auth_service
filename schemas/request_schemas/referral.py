from enum import Enum
from typing import Optional

from pydantic import BaseModel, Field, field_validator

from database.models.referral_reward import RewardStatus


class ReferralVisitIn(BaseModel):
    referral_code: str = Field(..., min_length=1, max_length=32, json_schema_extra={"example": "AB2CD3EF"})
    visitor_id: Optional[str] = Field(
        None,
        max_length=64,
        description="Stable anonymous visitor id generated by the frontend (localStorage/cookie)",
    )
    landing_url: Optional[str] = Field(None, max_length=2048)


class PayoutIn(BaseModel):
    amount_cents: int = Field(..., gt=0, description="Amount paid to the user, in cents")
    note: Optional[str] = Field(None, max_length=1000)
    external_reference: Optional[str] = Field(None, max_length=255, description="Bank transfer id or similar")


class AdjustmentIn(BaseModel):
    amount_cents: int = Field(..., description="Positive to credit, negative to debit, in cents")
    note: str = Field(..., min_length=1, max_length=1000)

    @field_validator("amount_cents")
    @classmethod
    def non_zero(cls, v: int) -> int:
        if v == 0:
            raise ValueError("amount_cents must not be zero")
        return v


class RewardActionIn(BaseModel):
    note: Optional[str] = Field(None, max_length=1000)


class RewardFilterIn(BaseModel):
    status: Optional[RewardStatus] = Field(None, description="Filter by reward status")


class ReferrerSortField(str, Enum):
    VISITS = "visits"
    REGISTRATIONS = "registrations"
    USERS_WITH_BIDS = "users_with_bids"
    PURCHASES_PAID = "purchases_paid"
    BALANCE = "balance_cents"
    TOTAL_EARNED = "total_earned_cents"
    CREATED_AT = "created_at"


class SortOrder(str, Enum):
    ASC = "asc"
    DESC = "desc"


class ReferrerSearchIn(BaseModel):
    search: Optional[str] = Field('', description='Search by email, first, last names, phone number, referral code')
    only_active: bool = Field(True, description='Only users with referral activity (visits, referrals or wallet)')
    sort_by: ReferrerSortField = Field(ReferrerSortField.REGISTRATIONS)
    order: SortOrder = Field(SortOrder.DESC)
